// ---- Code-node source -------------------------------------------------------------------------
/** A module made pasteable: import lines dropped, `export` keywords removed. */
const inline = (file) =>
  readFileSync(path.join(here, 'src', file), 'utf8')
    .replace(/^import .*$/gm, '')
    .replace(/^export (const|function|async function) /gm, '$1 ')
    .trim();
const LIB = `${inline('ledger.mjs')}\n${inline('invoices.mjs')}`;
