/** Deploy order: Alerts first (every other workflow names it as its error workflow). */
export const WORKFLOWS = [alerts, inbox, decision, weekly, tidy];

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = path.join(here, 'workflows');
  mkdirSync(out, { recursive: true });
  for (const wf of WORKFLOWS) {
    const file = `${wf.name.replace('Invoices · ', '').toLowerCase().replace(/[^a-z0-9]+/g, '-')}.json`;
    writeFileSync(path.join(out, file), JSON.stringify(wf, null, 2) + '\n');
    console.log(`${file.padEnd(22)} ${wf.nodes.length} nodes`);
  }
}
