const code = (body) => `// Generated by n8n/build.mjs from n8n/src. Edit the source files, not this node.\n${LIB}\n// ---- node logic ----\n${body.trim()}\n`;

// ---- Node helpers -------------------------------------------------------------------------------
const uuid = (seed) => {
  const h = createHash('sha256').update(seed).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const cred = (type, name) => ({ [type]: { id: `__CREDENTIAL__${name}`, name } });
const SHEETS = 'https://sheets.googleapis.com/v4/spreadsheets/__ENV__SHEET_ID';
const LEDGER_RANGE = encodeURIComponent("'Purchase ledger'");

function workflow(name, nodes, edges, settings = {}) {
  const names = new Set(nodes.map((n) => n.name));
  if (names.size !== nodes.length) throw new Error(`${name}: duplicate node names`);
  const connections = {};
  for (const [from, to, output = 0] of edges) {
    if (!names.has(from) || !names.has(to)) throw new Error(`${name}: edge ${from} -> ${to} names a missing node`);
    connections[from] ??= { main: [] };
    while (connections[from].main.length <= output) connections[from].main.push([]);
    connections[from].main[output].push({ node: to, type: 'main', index: 0 });
  }
  const wf = {
    name,
    nodes: nodes.map((n) => ({ id: uuid(`${name}/${n.name}`), ...n })),
    connections,
    settings: {
      executionOrder: 'v1',
      timezone: 'Europe/London',
      saveDataErrorExecution: 'all',
      saveDataSuccessExecution: 'all',
      ...(name === WF.alerts ? {} : { errorWorkflow: `__WORKFLOW__${WF.alerts}` }),
      ...settings,
    },
  };
  checkReferences(wf);
  return wf;
}

/** Every $("Node") mentioned in a workflow, to fail the build on a reference to a missing node. */
export function nodeReferences(wf) {
  const found = [];
  const walk = (v) => {
    if (typeof v === 'string') for (const m of v.matchAll(/\$\((["'])((?:(?!\1).)+)\1\)/g)) found.push(m[2]);
    else if (v && typeof v === 'object') Object.values(v).forEach(walk);
  };
  wf.nodes.forEach((n) => walk(n.parameters));
  return [...new Set(found)];
}
function checkReferences(wf) {
  const names = new Set(wf.nodes.map((n) => n.name));
  const missing = nodeReferences(wf).filter((r) => !names.has(r));
  if (missing.length) throw new Error(`${wf.name}: references to missing nodes: ${missing.join(', ')}`);
}

const codeNode = (name, position, body, mode = 'runOnceForAllItems') => ({
  name, type: 'n8n-nodes-base.code', typeVersion: 2, position,
  parameters: { mode, language: 'javaScript', jsCode: code(body) },
});
const webhookNode = (name, position, hookPath) => ({
  name, type: 'n8n-nodes-base.webhook', typeVersion: 2, position, webhookId: uuid(`webhook/${hookPath}`),
  parameters: { httpMethod: 'POST', path: hookPath, authentication: 'headerAuth', responseMode: 'responseNode', options: {} },
  credentials: cred('httpHeaderAuth', CRED.internal),
});
const respondNode = (name, position, bodyExpr) => ({
  name, type: 'n8n-nodes-base.respondToWebhook', typeVersion: 1.1, position,
  parameters: { respondWith: 'json', responseBody: bodyExpr, options: { responseCode: 200 } },
});
const ifTrue = (name, position, expr) => ({
  name, type: 'n8n-nodes-base.if', typeVersion: 2.2, position,
  parameters: {
    conditions: {
      options: { caseSensitive: true, leftValue: '', typeValidation: 'strict', version: 2 },
      conditions: [{ id: uuid(`${name}/cond`), leftValue: `={{ ${expr} }}`, rightValue: '', operator: { type: 'boolean', operation: 'true', singleValue: true } }],
      combinator: 'and',
    },
    options: {},
  },
});
/** Google Sheets REST call with the service-account credential. */
const sheetsNode = (name, position, method, url, bodyExpr) => ({
  name, type: 'n8n-nodes-base.httpRequest', typeVersion: 4.2, position,
  parameters: {
    method, url,
    authentication: 'predefinedCredentialType', nodeCredentialType: 'googleApi',
    ...(bodyExpr ? { sendBody: true, specifyBody: 'json', jsonBody: bodyExpr } : {}),
    options: { timeout: 20000 },
  },
  credentials: cred('googleApi', CRED.google),
  retryOnFail: true, maxTries: 3, waitBetweenTries: 2000,
});
const slackNode = (name, position, method, bodyExpr) => ({
  name, type: 'n8n-nodes-base.httpRequest', typeVersion: 4.2, position,
  parameters: {
    method: 'POST', url: `https://slack.com/api/${method}`,
    authentication: 'predefinedCredentialType', nodeCredentialType: 'slackApi',
    sendHeaders: true, headerParameters: { parameters: [{ name: 'Content-Type', value: 'application/json; charset=utf-8' }] },
    sendBody: true, specifyBody: 'json', jsonBody: bodyExpr, options: { timeout: 15000 },
  },
  credentials: cred('slackApi', CRED.slack),
  retryOnFail: true, maxTries: 3, waitBetweenTries: 1000,
});
const readLedger = (name, position) =>
  sheetsNode(name, position, 'GET', `${SHEETS}/values/${LEDGER_RANGE}!A2:T?valueRenderOption=UNFORMATTED_VALUE`);
const rowsFrom = (node) => `($('${node}').first().json.values ?? []).map((v, i) => rowToObject(v, i + 2))`;
const schedule = (name, position, rule) => ({ name, type: 'n8n-nodes-base.scheduleTrigger', typeVersion: 1.2, position, parameters: { rule: { interval: [rule] } } });

