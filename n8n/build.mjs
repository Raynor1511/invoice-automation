// Don't edit the JSON by hand. Run: node n8n/build.mjs
// Deployment-specific values stay placeholders until n8n/deploy.mjs fills them in:
//   __ENV__NAME (settings), __CREDENTIAL__name and __WORKFLOW__name (n8n ids).
